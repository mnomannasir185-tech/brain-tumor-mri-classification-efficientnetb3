# ===================== TTA =====================
def tta_predict(model, imgs):
    preds = []
    preds.append(model(imgs))
    preds.append(model(torch.flip(imgs, dims=[3])))
    preds.append(model(torch.rot90(imgs, 1, dims=[2,3])))
    preds.append(model(torch.rot90(imgs, 2, dims=[2,3])))
    return torch.mean(torch.stack(preds), dim=0)

