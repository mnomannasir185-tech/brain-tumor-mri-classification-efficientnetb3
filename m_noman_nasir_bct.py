    def __init__(self, mode="dual"):
        super().__init__()

        self.mode = mode

        self.backbone1 = efficientnet_b3(weights=EfficientNet_B3_Weights.DEFAULT)
        self.backbone1.classifier = nn.Identity()

        self.backbone2 = efficientnet_b3(weights=EfficientNet_B3_Weights.DEFAULT)
        self.backbone2.classifier = nn.Identity()

        if mode == "dual":
            in_features = 1536 * 2
        else:
            in_features = 1536

        self.fc = nn.Sequential(
            nn.Linear(in_features, 256),
            nn.ReLU(),
            nn.Dropout(0.5),
            nn.Linear(256, 3)
        )

    def forward(self, img, roi):
        if self.mode == "image":
            feat = self.backbone1(img)

        elif self.mode == "roi":
            feat = self.backbone2(roi)

        else:  # dual
            f1 = self.backbone1(img)
            f2 = self.backbone2(roi)
            feat = torch.cat([f1, f2], dim=1)

        return self.fc(feat)

    def forward(self, img, roi):
        return self.fc(torch.cat([self.b1(img), self.b2(roi)], dim=1))

