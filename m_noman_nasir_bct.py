    val_idx   = [i for pid in val_pids   for i in patient_dict[pid]]

    print(f"Train samples: {len(train_idx)} | Val samples: {len(val_idx)}")

    train_loader = DataLoader(DualDataset(train_idx, True), batch_size=BATCH_SIZE, shuffle=True)
    val_loader   = DataLoader(DualDataset(val_idx, False), batch_size=BATCH_SIZE)

    MODEL_TYPE = "dual"   # 👈 ONLY CHANGE THIS LINE

    print("Running:", MODEL_TYPE)

    model = BrainTumorModel(mode=MODEL_TYPE).to(device)

    for p in model.parameters(): p.requires_grad = False
    for p in model.fc.parameters(): p.requires_grad = True

    optimizer = torch.optim.AdamW(model.parameters(), lr=1e-4)
    criterion = nn.CrossEntropyLoss(label_smoothing=0.1)

    best_acc = 0

    for epoch in range(EPOCHS):

        if epoch == 3:
            for p in model.b1.features[-2:].parameters(): p.requires_grad = True
            for p in model.b2.features[-2:].parameters(): p.requires_grad = True

        if epoch == 8:
            for p in model.parameters(): p.requires_grad = True

        model.train()
        for imgs, rois, y in train_loader:
            imgs, rois, y = imgs.to(device), rois.to(device), y.to(device)
            optimizer.zero_grad()
            loss = criterion(model(imgs, rois), y)
