class DualDataset(Dataset):
    def __init__(self, indices, augment=False):
        self.indices = indices
        self.augment = augment

    def __len__(self):
        return len(self.indices)

    def __getitem__(self, idx):
        i = self.indices[idx]

        img = np.load(f"{data_dir}/img_{i}.npy")
        roi = np.load(f"{data_dir}/roi_{i}.npy")
        lbl = int(np.load(f"{data_dir}/label_{i}.npy"))

        img = (img - img.mean()) / (img.std() + 1e-8)
        roi = (roi - roi.mean()) / (roi.std() + 1e-8)

        if self.augment and np.random.rand() > 0.5:
            img = np.fliplr(img)
            roi = np.fliplr(roi)

        img = np.stack([img]*3)
        roi = np.stack([roi]*3)

        return torch.tensor(img, dtype=torch.float32), \
               torch.tensor(roi, dtype=torch.float32), \
               torch.tensor(lbl, dtype=torch.long)

