class DualModel(nn.Module):
    def __init__(self):
        super().__init__()

        self.backbone_img = efficientnet_b3(weights=EfficientNet_B3_Weights.DEFAULT)
        self.backbone_roi = efficientnet_b3(weights=EfficientNet_B3_Weights.DEFAULT)

        self.backbone_img.classifier = nn.Identity()
        self.backbone_roi.classifier = nn.Identity()

        self.fc = nn.Sequential(
            nn.Linear(1536*2, 256),
            nn.ReLU(),
            nn.Dropout(0.5),
            nn.Linear(256, 3)
        )

    def forward(self, img, roi):
        f1 = self.backbone_img(img)
        f2 = self.backbone_roi(roi)

        x = torch.cat([f1, f2], dim=1)
        return self.fc(x)

